def references(doc, entries):
    doc.add_heading("References", 1)
    for key, entry in sorted(entries.items(), key=lambda item: unicodedata.normalize("NFKD",
                             base.decode_latex_text(item[1]["author"])).casefold()):
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Inches(0.25)
        p.paragraph_format.first_line_indent = Inches(-0.25)
        p.paragraph_format.line_spacing = 1.1
        p.paragraph_format.space_after = Pt(3)
        authors = []
        for value in entry["author"].split(" and "):
            value = base.decode_latex_text(value)
            family, given = value.split(",", 1)
            initials = " ".join("-".join(part[0] + "." for part in token.split("-") if part)
                                for token in given.strip().split())
            authors.append(f"{family}, {initials}")
        author_text = ", ".join(authors[:-1]) + ", & " + authors[-1] if len(authors) > 1 else authors[0]
        title = base.decode_latex_text(entry["title"]).rstrip(".")
        ending = "" if title.endswith(("?", "!")) else "."
        text_run(p, f"{author_text} ({entry['year']}). {title}{ending} ", size=10)
        container = base.decode_latex_text(entry.get("journal", entry.get("booktitle", "")))
        text_run(p, container, italic=True, size=10)
        if entry.get("volume"):
            text_run(p, ", " + entry["volume"], italic=True, size=10)
        if entry.get("number"):
            text_run(p, "(" + entry["number"] + ")", size=10)
        if entry.get("pages"):
            text_run(p, ", " + entry["pages"].replace("--", "–"), size=10)
        text_run(p, ".", size=10)
        if entry.get("doi"):
            text_run(p, " https://doi.org/" + entry["doi"], size=10)
        elif key == "he2008active":
            text_run(p, " https://www.jmlr.org/papers/v9/he08a.html", size=10)
        elif key == "moldovan2012safe":
            text_run(p, " https://icml.cc/2012/papers/838.pdf", size=10)


def add_theorem(doc, label, raw, entries):
    start = len(doc.paragraphs)
    p = doc.add_paragraph()
    text_run(p, base.latex_plain(label, entries) + ".", bold=True)
    p.paragraph_format.keep_with_next = True
    for index, part in enumerate(re.split(r"\[\[EQ:(\d+)\]\]", raw)):
        if index % 2:
            add_equation(doc, int(part))
        elif part.strip():
            paragraph(doc, revise(base.latex_plain(part, entries)))
    for p in doc.paragraphs[start:-1]:
        p.paragraph_format.keep_with_next = True


def load_entries():
    entries = base.parse_bib(base.BIB.read_text())
    metadata = json.loads((REVISED / "reference_metadata.json").read_text())
    for key, result in metadata.items():
        if result.get("match_score", 0) >= 0.98:
            entries[key]["doi"] = result["record"]["DOI"]
    # Verified against the original publisher's record.
    entries["chaloner1995bayesian"]["doi"] = "10.1214/ss/1177009939"
    return entries


