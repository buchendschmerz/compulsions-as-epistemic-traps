def author_year(key, entries, narrative=False):
    entry = entries[key]
    names = [base.decode_latex_text(value.split(",", 1)[0])
             for value in entry["author"].split(" and ") if value != "others"]
    if key in ("fradkin2020searching", "fradkin2020latent"):
        lead = f"{names[0]}, {names[1]}, et al."
    elif len(names) > 2:
        lead = names[0] + " et al."
    elif len(names) == 2:
        lead = (" and " if narrative else " & ").join(names)
    else:
        lead = names[0]
    return f"{lead} ({entry['year']})" if narrative else f"{lead}, {entry['year']}"


