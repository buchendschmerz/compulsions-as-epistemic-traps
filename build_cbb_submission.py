def add_equation(doc, number, lines=None):
    if lines is None:
        base.add_equation_native(doc, number)
    else:
        original = base._equation_lines
        base._equation_lines = lambda value: lines if value == number else original(value)
        try:
            base.add_equation_native(doc, number)
        finally:
            base._equation_lines = original
    p = doc.paragraphs[-1]
    p.paragraph_format.keep_with_next = False
    p.paragraph_format.line_spacing = 1.2
    for run in p.runs:
        run.font.color.rgb = RGBColor(0, 0, 0)
        if run.text == f"\t({number})":
            display_number = {1: 1, 2: 2, 3: 4, 4: 5, 5: 6, 6: 3}[number]
            run.text = f"\t({display_number})"


def math_append(parent, value):
    if isinstance(value, (list, tuple)):
        for item in value:
            math_append(parent, item)
    elif isinstance(value, str):
        for token in re.findall(r"[A-Za-z]+|[α-ωΑ-Ω]|[^A-Za-zα-ωΑ-Ω]+", value):
            run = base._math_run(token)
            properties = OxmlElement("m:rPr")
            style = OxmlElement("m:sty")
            style.set(qn("m:val"), "i" if len(token) == 1 and token.isalpha() else "p")
            properties.append(style)
            run.insert(0, properties)
            parent.append(run)
    else:
        parent.append(value)


base._append_math = math_append

