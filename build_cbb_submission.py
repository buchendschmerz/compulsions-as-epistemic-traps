def text_run(paragraph, text, bold=False, italic=False, size=None):
    run = paragraph.add_run(text)
    run.bold, run.italic = bold, italic
    run.font.name = "Times New Roman"
    run.font.color.rgb = RGBColor(0, 0, 0)
    if size:
        run.font.size = Pt(size)
    return run


def paragraph(doc, text, style=None):
    text = text.replace("(1-p)^k", "(1 − p)ᵏ").replace("(1 − p)^k", "(1 − p)ᵏ")
    result = doc.add_paragraph(style=style)
    for token in re.split(r"(\b[qpkY]\b|\b[ab]_z\b)", text):
        if token in {"a_z", "b_z"}:
            math = OxmlElement("m:oMath")
            math.append(base._math_sub(token[0], "z"))
            result._p.append(math)
        else:
            text_run(result, token, italic=token in {"q", "p", "k", "Y"})
    return result


